def all_codes() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    for group, items in GROUPS:
        for code, title in items:
            out.append({"code": code, "title": title, "group": group})
    return out


def title_for(code: str) -> str:
    code = (code or "").strip()
    for item in all_codes():
        if item["code"] == code:
            return item["title"]
    return ""
